## Даалгавар

Хэрэглэгч файл хавсаргаж санал хүсэлт илгээдэг формыг frontend болон backend-тэй нь цогцоор бүтээнэ.

Форм нь бот, duplicate илгээлт, хэт олон спам хүсэлтээс хамгаалагдсан байх бөгөөд хэрэглэгчдэд форм бөглөхөд хэт ядаргаатай олон хамгаалалтыг давах саадгүй байх ёстой.

Тухайн формыг өөрийн дуртай програмчлалын хэл болон сангаа сонгон бүтээлчээр аль болох хэрэглэгчид хялбар, зөв форматтай, зөв мэдээллийг хүлээн авах хамгаалалт сайтай байдлаар хийж гүйцэтгэнэ.

## Формын талбарууд

- **name** — Заавал, 1–100 тэмдэгт
- **email** — Заавал, зөв формат
- **number** — Утасны дугаар, улсын кодлолт сонголттой
- **topic** — "Асуулт", "Санал", "Гомдол"-оос сонгох боломжтой
- **message** — 10–2000 тэмдэгт, зөвхөн кирил үсгээр
- **files** — 0–3 файл; JPG, PNG, WEBP эсвэл PDF; тус бүр 5 MB хүртэл
- **checkbox** — Жишээ хэрэглэгчийн нууцлалын бодлогын чекбокс

## Шаардлага

**Frontend**

- Хэрэглэгчид ойлгомжтой, хялбар шийдэлтэй байх.
- Нээлттэй даалгавар тул бүтээлч сэтгэлгээ, заавалчгүй байх UI/UX шийдлүүдийг тусгах.

**Backend**

- Хэрэглэгчийн өгөгдлийг зөв форматтай, цэгцтэй, аюулгүй, хайлт хийхэд хялбар, хурдан байдлаар шийдэх.
- Нээлттэй даалгавар тул бүтээлч сэтгэлгээ ашиглан аюулгүй байдлын болон бусад шийдлүүдийг тусгах.

